				<span class="h4 pull-left m-15" style="font-size: 11.5pt; color: #777; padding-left:14pt;">(2019.12.10.)</span>
		<p class="pull-right date finished">(<nobr>리행한</nobr> <nobr>실례</nobr>)</p><div class="clearfix"></div><p><u>대상계획명</u>:사리원시 구룡고급중학교건설 및 망하부구조 구축</p>

<p><u>해외기증자</u>: 인터내셔널 베텔비젼단체</p>

<p><u>대상계획목적</u>: 큰물피해를 입은 구룡고급중학교 교사를 새로 건설하고 국가콤퓨터망에 련결하여 교원들과 학생들에게 개선된 교육조건과 환경을 보장해주는데 있다.</p>

<p><u>혜택자수</u>: 900여명의 구룡고급중학교 학생들과 45명의 교직원들</p>

<p><u>대상계획리행기간</u>: 2017년 4월 - 2018년 9월 (학교건설)<br />
&nbsp; &nbsp; &nbsp; &nbsp; &nbsp; &nbsp; &nbsp; &nbsp; &nbsp; &nbsp; &nbsp; &nbsp; &nbsp; &nbsp; &nbsp; &nbsp; &nbsp;2019년 3월 - 5월 (망하부구조 구축)</p>

<p><u>활동내용</u>: 2017년 4월 조선교육후원기금은 이미 건설중에 있던 구룡고급중학교건설제안서를 기증단체에 제출하여 협조계획을 합의하였다.</p>

<p>합의에 따라 해외기증단체는 강재를, 국내단체는 세멘트와 강재, 골재를 비롯한 건설자재와 로력을 보장하였다. 학교건설은 1단계로서 2017년 11월까지 3층골조공사를 완공하였고 2단계로서 2018년 9월까지 지붕공사와 외내부미장공사, 주변지대정리를 진행하였다. 연건평이 4천㎡인 3층교사는 2018년 10월에 개교식을 진행하였다.</p>

<p>조선교육후원기금은 9차에 걸쳐 학교건설정형을 료해하였으며 2017년 8월 기증단체와 현지를 참관하여 건설정형을 료해하였다.</p>

<p>기증단체는 2018년 11월 완공된 학교를 참관하여 대상리행정형을 평가하고 다음 단계협조로 학교의 교육정보화설비를 후원하기로 토의하였다.</p>

<p>2019년 5월 조선교육후원기금은 기증단체와 함께 콤퓨터와 액정TV, 망설비 등을 비롯한 교육정보설비들을 후원하였다.</p>

<p><u>결과</u>: 900여명의 학생들이 사계절 불편없이 공부할수 있게 되였으며 국가콤퓨터망을 통하여 우수한 교육방법들을 정상적으로 보급일반화할수 있게 되였다.</p>

