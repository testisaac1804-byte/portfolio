		function containsEnglishAB(text) {
			var i;
			for(i=0; i<text.length; i++) {
				var code = text.charCodeAt(i);
				if((code >= 65 && code <= 90) || (code >= 97 && code <= 123) ||(code == 39))
					return true;
			}
		}
